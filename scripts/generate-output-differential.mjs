// Output differential of phase 2 and 6 (ADR 0001): the four commands of the first slice must return
// the same values in Rust as the TypeScript application returns, for the database that each of the nine
// tagged release lines (0.5.0-beta to 1.0.2) writes.
//
//   node scripts/generate-output-differential.mjs
//
// The bases come from `scripts/release-lines.mjs`: each line writes its own synthetic database with its
// own code, and the current TypeScript code upgrades a copy of it. The current TypeScript code reads the
// settings, the workspaces with their availability, and the conversations of that copy (`base`). Then
// the TypeScript repositories write a few values that are not defaults on the copy, and the same reading
// is taken again (`written`). Both go to `target/output-differential/expected.json`.
// `crates/noct-app/tests/output_differential.rs` upgrades the legacy file in Rust and compares `base`, and
// opens the written copy and compares `written`. Everything is generated on each run and nothing is committed: the
// conversation identifiers and the timestamps differ from run to run. Paths are written relative to the
// gate directory.
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { writeReleaseLines, readPins } from './release-lines.mjs'

const root = path.resolve(import.meta.dirname, '..')
const requireFromRoot = createRequire(path.join(root, 'package.json'))
const ts = requireFromRoot('typescript')
const gateDirectory = path.join(root, 'target', 'output-differential')
const buildDirectory = path.join(root, 'node_modules', '.cache', 'noct-output-differential')
// The expected outputs are written next to the bases, not committed: the conversation identifiers and the
// timestamps are generated by the TypeScript code on every run, so the reference is the run itself.
const expectedFile = path.join(gateDirectory, 'expected.json')

// The contract fields, in the order the Rust output serializes them.
const SETTINGS_FIELDS = ['approvalPolicy', 'diagnosticMode', 'theme', 'language', 'pandocVersion']
const WORKSPACE_FIELDS = ['path', 'name', 'favorite', 'authorized', 'availability', 'availabilityMessage', 'createdAt', 'lastOpenedAt']
const CONVERSATION_FIELDS = ['id', 'title', 'workspace', 'createdAt', 'updatedAt']

function compileTree(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const source = path.join(directory, entry.name)
    if (entry.isDirectory()) {
      compileTree(source)
      continue
    }
    if (!entry.name.endsWith('.ts') || entry.name.endsWith('.d.ts')) continue
    const output = path.join(buildDirectory, path.relative(root, source)).replace(/\.ts$/, '.js')
    const { outputText } = ts.transpileModule(fs.readFileSync(source, 'utf8'), {
      fileName: source,
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true },
    })
    fs.mkdirSync(path.dirname(output), { recursive: true })
    fs.writeFileSync(output, outputText)
  }
}

// Only the fields of the contract, and only those that are present: an absent optional stays absent.
function project(value, fields) {
  const projected = {}
  for (const field of fields) {
    if (value[field] !== undefined) projected[field] = value[field]
  }
  return projected
}

// Replaces the gate directory in every string, so the committed outputs do not depend on the machine.
function relocate(value, gate) {
  if (typeof value === 'string') return value.split(gate).join('<gate>')
  if (Array.isArray(value)) return value.map((item) => relocate(item, gate))
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, relocate(item, gate)]))
  }
  return value
}

// The TypeScript reading of the three collections, as the IPC handlers compose them:
// settings.get (readSettings), workspace.list (listWorkspaces with inspectWorkspaceScope) and
// conversations.list (listConversations).
function readOutputs(database, inspectWorkspaceScope) {
  const saved = database.getSettings()
  const settings = project({ ...saved, diagnosticMode: saved.diagnosticMode === 'true' }, SETTINGS_FIELDS)
  const workspaces = database.listWorkspaces().map((workspace) => {
    const inspection = inspectWorkspaceScope(workspace.path)
    return project(
      {
        ...workspace,
        authorized: workspace.authorized && inspection.availability === 'available',
        availability: inspection.availability,
        ...(inspection.message ? { availabilityMessage: inspection.message } : {}),
      },
      WORKSPACE_FIELDS,
    )
  })
  const conversations = database.listConversations().map((conversation) => project(conversation, CONVERSATION_FIELDS))
  return { settings, workspaces, conversations }
}

// Writes on the read copy only, through the TypeScript repositories, so that the outputs cover values
// that are not the defaults: every setting changed, a missing folder, and a file saved as a workspace.
// The Rust side reads the same copy, so these writes are part of both sides of the comparison.
function addReadingState(database, readDirectory) {
  database.setSettings({
    approvalPolicy: 'untrusted',
    diagnosticMode: 'true',
    theme: 'light',
    language: 'en',
    pandocVersion: '3.1.2',
  })
  database.touchWorkspace(path.join(readDirectory, 'missing-project'))
  const notes = path.join(readDirectory, 'notes.txt')
  fs.writeFileSync(notes, 'not a folder\n')
  database.touchWorkspace(notes)
}

export function generate() {
  fs.rmSync(gateDirectory, { recursive: true, force: true })
  fs.rmSync(buildDirectory, { recursive: true, force: true })
  fs.mkdirSync(gateDirectory, { recursive: true })
  for (const directory of ['electron', 'shared']) compileTree(path.join(root, directory))
  const requireBuild = createRequire(path.join(buildDirectory, 'probe.cjs'))
  const { LocalDatabase } = requireBuild('./electron/database/Database.js')
  const { inspectWorkspaceScope } = requireBuild('./electron/security/WorkspaceTrust.js')

  writeReleaseLines(gateDirectory, LocalDatabase)
  const gate = fs.realpathSync(gateDirectory)
  const manifest = JSON.parse(fs.readFileSync(path.join(gateDirectory, 'release-lines', 'manifest.json'), 'utf8'))
  const expectedTags = readPins().lines.map((line) => line.tag)
  const tags = manifest.lines.map((line) => line.tag)
  if (JSON.stringify(tags) !== JSON.stringify(expectedTags)) {
    throw new Error(`the bases are ${tags.join(', ')}, expected ${expectedTags.join(', ')}`)
  }

  const lines = manifest.lines.map((line) => {
    const readDirectory = path.join(gateDirectory, 'read', line.tag)
    fs.mkdirSync(readDirectory, { recursive: true })
    fs.copyFileSync(path.join(gateDirectory, line.reference), path.join(readDirectory, 'nocturne.db'))
    const database = new LocalDatabase(readDirectory)
    try {
      const base = relocate(readOutputs(database, inspectWorkspaceScope), gate)
      addReadingState(database, readDirectory)
      const written = relocate(readOutputs(database, inspectWorkspaceScope), gate)
      return { tag: line.tag, base, written }
    } finally {
      database.close()
    }
  })

  return `${JSON.stringify({ generatedBy: 'scripts/generate-output-differential.mjs', tags, lines }, null, 2)}\n`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = generate()
  fs.writeFileSync(expectedFile, text)
  console.log(`wrote ${path.relative(root, expectedFile)}`)
}
